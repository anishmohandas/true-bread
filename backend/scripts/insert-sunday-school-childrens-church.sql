Sunday School was given this name because it was traditionally conducted on Sundays. Sunday School began in 1780 through the efforts of Robert Raikes, a layman and journalist from Gloucester, England.

During the second half of the eighteenth century, England was undergoing a major transition from an agrarian society to an industrial one. The lives of many families, particularly those belonging to the poorer sections of society, were miserable. Many families faced severe social and economic difficulties, and in some cases, the absence of fathers left mothers and older children responsible for caring for the entire family.

The First Industrial Revolution, which began around 1760, offered some hope of employment. The invention and development of steam power led to rapid growth in mechanical production, particularly in the textile and iron industries.

During this period, many children were employed in factories and other workplaces from Monday to Saturday. Sunday was often their only day of rest. Most of these children had little or no access to education and were vulnerable to exploitation by their employers. Nevertheless, the small wages they received at the end of the working week gave them an opportunity to seek entertainment on Sundays.

Thus, their lives followed a routine of employment and exploitation during the weekdays and unrestricted enjoyment on Sundays.

The streets of England often witnessed children fighting, engaging in immoral activities, and getting involved in various forms of misconduct, particularly on Sundays. Many of them lacked proper parental supervision, education, and moral guidance.

Robert Raikes witnessed these troubling conditions and began investigating the circumstances by speaking with mothers in the local community.

As a journalist, Raikes had already been making efforts to reform prisoners and draw public attention to their difficult circumstances through his newspaper. However, he found that changing the lives of adults was extremely challenging. He gradually realized that investing in children and shaping their lives at an early age could be a more effective way of bringing about lasting social change.

With this understanding, Raikes turned his attention towards children.

On Sundays, when the children were free from work, he invited them to attend classes where they could learn the alphabet, reading, writing, arithmetic, and other basic skills. He encouraged their participation by offering rewards and sweets. He also set aside time for teaching the Scriptures and helping them develop good moral character and become responsible citizens.

Gradually, his efforts began to bear fruit. Positive changes became evident in the lives of the children, and more parents were encouraged to send their children to Sunday School. Within approximately twenty years, Sunday School membership in Britain had grown to around 200,000.

<strong>Opposition to the Sunday School Movement</strong>

Although Sunday School rendered a valuable service to families and society, it initially faced opposition from several sections of the community, including some church authorities.

Some members of the clergy opposed the movement, interpreting the teaching activities on Sundays as a violation of the Fourth Commandment concerning the Sabbath.

Factory owners also opposed the initiative because they feared that education would make children more aware of their exploitation and less willing to accept unfair working conditions. Some members of the wealthy classes were similarly concerned that educating poor children would threaten the availability of cheap child labour.

Despite these challenges, Raikes continued his work with the support of compassionate individuals who loved God and cared deeply about the welfare of children.

Gradually, the Sunday School movement spread to the United States, other European countries, and regions across the world. Many countries embraced this ministry, and the Church eventually came to recognize its spiritual and social significance.

The emergence of Sunday School was rooted in a deep concern for children and a desire to protect them from illiteracy, exploitation, destructive influences, and immoral behaviour. It offered families in the eighteenth century renewed hope for their children’s future. For many, it seemed like an intervention from the Lord, bringing light into a world of darkness.

<strong>The Threefold Purpose of Sunday School Today</strong>

The purpose of Sunday School today can be understood in three ways:

1. <strong>To lead the unsaved to Christ:</strong> To introduce children to Jesus Christ and help them experience the saving love and grace of God.
2. <strong>To preserve and strengthen their faith:</strong> To help those who have accepted Christ remain steadfast in their faith and resist the evil influences of the world.
3. <strong>To nurture spiritual maturity and witness:</strong> To strengthen their faith, devotion, and understanding of God’s Word so that they may grow into mature Christians and share God’s saving love with others.

<strong>Sunday School in India</strong>

Sunday School also has a long history in India.

The first Sunday School in India is traditionally associated with the missionary work of William Carey and his associates in Serampore in 1803. Teaching was conducted in Bengali and English.

The India Sunday School Union was founded in Allahabad in 1876.

In Kerala, formal Sunday School activities are traditionally associated with Mallappally, where CSI Archdeacon Oommen Mammen started a Sunday School in 1880.

The Mar Thoma Sunday School Samajam was officially established in February 1905 during the Maramon Convention.

These developments demonstrate how the Sunday School movement gradually took root in India and became an important part of Christian education and spiritual formation.

